export const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun', 'Jul', 'Agu', 'Sep', 'Okt', 'Nov', 'Des'];

export function getMonthIndex(tgl: string): number {
  const parts = tgl.split('/');
  if (parts.length >= 2) {
    const monthNum = parseInt(parts[1], 10);
    if (!isNaN(monthNum) && monthNum >= 1 && monthNum <= 12) {
      return monthNum - 1;
    }
  }
  return 0;
}

export function getRecordYear(tgl?: string, srt?: string): string {
  if (tgl) {
    const clean = tgl.trim();
    const parts = clean.split('/');
    if (parts.length === 3) {
      let y = parts[2].trim();
      if (y.length === 2) y = '20' + y;
      if (/^20\d{2}$/.test(y)) return y;
    }
    const matchTgl = clean.match(/\b(20\d{2})\b/);
    if (matchTgl) return matchTgl[1];
  }
  if (srt) {
    const matchSrt = srt.match(/\b(20\d{2})\b/);
    if (matchSrt) return matchSrt[1];
  }
  return '2026';
}
