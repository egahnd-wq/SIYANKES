import type { EvacuationRecord, PatientCategory, EvacuationStatus } from '../types/evacuation.ts';

export function determineCategory(nama: string, identitas: string, patientStatus?: string): PatientCategory {
  const cleanNama = (nama || '').toLowerCase().trim();
  const cleanIdentitas = (identitas || '').toLowerCase().trim();
  const cleanStatus = (patientStatus || '').toLowerCase().trim();
  const combined = cleanNama + ' ' + cleanIdentitas + ' ' + cleanStatus;
  
  // 1. ANAK (An., a/d., a/n, anak)
  if (
    cleanNama.startsWith('an.') ||
    cleanNama.startsWith('an ') ||
    /(^|[\s(])a\/[dn]([\s.)/]|$)/.test(cleanIdentitas) ||
    combined.includes('anak')
  ) {
    return 'ANAK';
  }

  // 2. PNS / PPPK / ASN / HONORER (checked before PERSIT so "PNS III/d" never matches "i/d")
  if (
    /\b(pns|pppk|asn|honorer)\b/.test(combined)
  ) {
    return 'PNS';
  }
  
  // 3. PERSIT (Ny., i/d., i/s, istri, persit)
  if (
    cleanNama.startsWith('ny.') ||
    cleanNama.startsWith('ny ') ||
    /(^|[\s(])i\/[ds]([\s.)/]|$)/.test(cleanIdentitas) ||
    /(^|[\s(])i\.d([\s.)/]|$)/.test(cleanIdentitas) ||
    combined.includes('istri') ||
    combined.includes('persit')
  ) {
    return 'PERSIT';
  }
  
  // 4. Otherwise: MILITER
  return 'MILITER';
}

export function determineStatus(ket: string, srt: string): EvacuationStatus {
  const note = ((ket || '') + ' ' + (srt || '')).toLowerCase();
  if (note.includes('meninggal') || note.includes('gugur') || /\bmd\b/.test(note)) return 'MENINGGAL';
  if (note.includes('batal') || note.includes('dibatalkan')) return 'BATAL';
  if (note.includes('ralat') || note.includes('diralat')) return 'RALAT';
  if (note.includes('draft') || note.includes('proses')) return 'DALAM_PROSES';
  return 'SELESAI';
}

export function isRecordSembuh(r?: Partial<EvacuationRecord> | null): boolean {
  if (!r) return false;
  if (r.isSembuh === true) return true;
  if (r.isSembuh === false && r.lastEditedAt) return false;
  
  const text = ((r.ket || '') + ' ' + (r.srt || '') + ' ' + (r.catatanSembuh || '')).toLowerCase();
  return (
    text.includes('sembuh') ||
    text.includes('kembali ke satuan') ||
    text.includes('kembali ke kesatuan') ||
    text.includes('kembali satuan') ||
    text.includes('pulang ke satuan') ||
    text.includes('selesai rawat') ||
    text.includes('selesai berobat')
  );
}

